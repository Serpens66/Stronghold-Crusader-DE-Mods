        internal static bool MatchesMappedImage(ReadOnlySpan<byte> image, out string error)
        {
            foreach (Entry entry in All)
                if (!Matches(image, entry.Rva, entry.Bytes)) { error = entry.Name + " signature mismatch at RVA 0x" + entry.Rva.ToString("X") + "."; return false; }
            error = null;
            return true;
        }

        internal static bool MatchesPeImage(byte[] image)
        {
            foreach (Entry entry in All)
            {
                int offset = RvaToFileOffset(image, entry.Rva);
                if (offset < 0 || !Matches(image, offset, entry.Bytes)) return false;
            }
            return true;
        }

        private static bool Matches(ReadOnlySpan<byte> image, int offset, byte[] expected)
        {
            if (offset < 0 || offset + expected.Length > image.Length) return false;
            for (int index = 0; index < expected.Length; index++) if (image[offset + index] != expected[index]) return false;
            return true;
        }

        internal static int RvaToFileOffset(byte[] image, int rva)
        {
            if (image == null || image.Length < 0x40) return -1;
            int pe = BitConverter.ToInt32(image, 0x3C);
            if (pe < 0 || pe + 24 > image.Length || BitConverter.ToUInt32(image, pe) != 0x00004550) return -1;
            int sections = BitConverter.ToUInt16(image, pe + 6);
            int optionalSize = BitConverter.ToUInt16(image, pe + 20);
            int section = pe + 24 + optionalSize;
            for (int index = 0; index < sections; index++, section += 40)
            {
                if (section + 40 > image.Length) return -1;
                int virtualSize = BitConverter.ToInt32(image, section + 8);
                int virtualAddress = BitConverter.ToInt32(image, section + 12);
                int rawSize = BitConverter.ToInt32(image, section + 16);
                int rawAddress = BitConverter.ToInt32(image, section + 20);
                int size = Math.Max(virtualSize, rawSize);
                if (rva >= virtualAddress && rva < virtualAddress + size) return rawAddress + rva - virtualAddress;
            }
            return -1;
        }

